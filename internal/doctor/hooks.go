package doctor

import (
	"bytes"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

// HookFile is one script in a hooks directory.
type HookFile struct {
	Name      string `json:"name"`
	Path      string `json:"path"` // absolute
	Rel       string `json:"rel"`  // relative to the repository root
	Size      int64  `json:"size"`
	Exec      bool   `json:"executable"`
	Shebang   string `json:"shebang,omitempty"`
	CRLF      bool   `json:"crlf,omitempty"`
	BOM       bool   `json:"bom,omitempty"`
	Owner     string `json:"owner,omitempty"` // husky | lefthook | pre-commit | simple-git-hooks | custom
	SourcedBy string `json:"-"`               // set when a wrapper runs the file with sh (Husky v9)
	Content   []byte `json:"-"`
}

var ignoredHookFiles = map[string]bool{
	".gitignore": true, ".gitkeep": true, "README": true, "README.md": true, "husky.sh": true,
	"h": true, ".DS_Store": true, "Thumbs.db": true,
}

// ReadHookDir lists the hook scripts in dir. Sample files and helper
// directories are skipped; unknown names are returned with Name set so the
// caller can report them as misnamed.
func ReadHookDir(dir string, repo *Repo) []*HookFile {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	var out []*HookFile
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || strings.HasSuffix(name, ".sample") || ignoredHookFiles[name] || strings.HasSuffix(name, "~") {
			continue
		}
		hf := ReadHook(filepath.Join(dir, name), repo)
		if hf != nil {
			out = append(out, hf)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// ReadHook reads and classifies one hook file.
func ReadHook(path string, repo *Repo) *HookFile {
	info, err := os.Stat(path)
	if err != nil || info.IsDir() {
		return nil
	}
	data, _ := os.ReadFile(path)
	hf := &HookFile{Name: filepath.Base(path), Path: path, Rel: repo.Rel(path), Size: info.Size(), Content: data}
	hf.Exec = runtime.GOOS == "windows" || info.Mode()&0o111 != 0
	hf.BOM = bytes.HasPrefix(data, []byte{0xEF, 0xBB, 0xBF})
	hf.CRLF = bytes.Contains(data, []byte("\r\n"))
	body := bytes.TrimPrefix(data, []byte{0xEF, 0xBB, 0xBF})
	if bytes.HasPrefix(body, []byte("#!")) {
		line, _, _ := bytes.Cut(body, []byte("\n"))
		hf.Shebang = strings.TrimSpace(strings.TrimSuffix(string(line[2:]), "\r"))
	}
	s := string(data)
	switch {
	case strings.Contains(s, "File generated by pre-commit"):
		hf.Owner = "pre-commit"
	case strings.Contains(s, "lefthook"):
		hf.Owner = "lefthook"
	case strings.Contains(s, "husky"):
		hf.Owner = "husky"
	case strings.Contains(s, "SKIP_SIMPLE_GIT_HOOKS") || strings.Contains(s, "simple-git-hooks"):
		hf.Owner = "simple-git-hooks"
	default:
		hf.Owner = "custom"
	}
	return hf
}

// Interpreter returns the program a shebang runs ("sh", "node", "python3").
func Interpreter(shebang string) (prog string, absolute string) {
	fields := strings.Fields(shebang)
	if len(fields) == 0 {
		return "", ""
	}
	if filepath.Base(fields[0]) == "env" {
		for _, f := range fields[1:] {
			if strings.HasPrefix(f, "-") || strings.Contains(f, "=") {
				continue
			}
			return f, ""
		}
		return "", ""
	}
	return filepath.Base(fields[0]), fields[0]
}

// SuggestHookName returns the Git hook a misnamed file was probably meant to be.
func SuggestHookName(name string) string {
	base := strings.ToLower(name)
	for _, ext := range []string{".sh", ".bash", ".zsh", ".js", ".cjs", ".mjs", ".ts", ".py", ".rb", ".pl", ".ps1", ".bat", ".cmd", ".exe", ".txt", ".hook"} {
		base = strings.TrimSuffix(base, ext)
	}
	base = strings.ReplaceAll(base, "_", "-")
	if IsGitHook(base) {
		return base
	}
	best, bestDist := "", 3
	for _, h := range GitHooks {
		if strings.ReplaceAll(h, "-", "") == strings.ReplaceAll(base, "-", "") {
			return h
		}
		if d := levenshtein(base, h); d < bestDist {
			best, bestDist = h, d
		}
	}
	return best
}

func levenshtein(a, b string) int {
	prev := make([]int, len(b)+1)
	cur := make([]int, len(b)+1)
	for j := range prev {
		prev[j] = j
	}
	for i := 1; i <= len(a); i++ {
		cur[0] = i
		for j := 1; j <= len(b); j++ {
			cost := 1
			if a[i-1] == b[j-1] {
				cost = 0
			}
			cur[j] = min(prev[j]+1, cur[j-1]+1, prev[j-1]+cost)
		}
		prev, cur = cur, prev
	}
	return prev[len(b)]
}

// toolsToCheck are commands hooks commonly call that GUI Git clients often
// cannot find (their PATH does not include nvm, pyenv, asdf, ...).
var toolsToCheck = map[string]bool{
	"npx": true, "npm": true, "pnpm": true, "yarn": true, "bun": true, "bunx": true, "node": true, "deno": true,
	"python": true, "python3": true, "pre-commit": true, "lefthook": true, "php": true, "composer": true,
	"go": true, "cargo": true, "dotnet": true, "ruby": true, "bundle": true, "lint-staged": true,
	"commitlint": true, "prettier": true, "eslint": true, "pnpx": true, "uv": true, "uvx": true, "poetry": true,
}

// CommandsUsed returns the first word of each command line in a shell hook,
// limited to well-known tools, with 1-based line numbers.
func CommandsUsed(content []byte) map[string]int {
	out := map[string]int{}
	for i, line := range strings.Split(strings.ReplaceAll(string(content), "\r\n", "\n"), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		for _, part := range splitCommands(line) {
			fields := strings.Fields(part)
			for len(fields) > 0 && (strings.Contains(fields[0], "=") || fields[0] == "exec" || fields[0] == "command" || fields[0] == "!") {
				fields = fields[1:]
			}
			if len(fields) == 0 {
				continue
			}
			if toolsToCheck[fields[0]] {
				if _, seen := out[fields[0]]; !seen {
					out[fields[0]] = i + 1
				}
			}
		}
	}
	return out
}

func splitCommands(line string) []string {
	r := strings.NewReplacer("&&", "\n", "||", "\n", ";", "\n", "|", "\n")
	return strings.Split(r.Replace(line), "\n")
}
